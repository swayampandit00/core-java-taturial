public class VariablesExample {
    public static void main(String[] args) {
        int a = 10;
        double b = 5.5;
        char c = 'A';
        String name = "Java";

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(name);
    }
}